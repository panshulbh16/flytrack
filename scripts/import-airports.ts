// Generates supabase/seed.sql with every airport that has an IATA code (name, lat/lon, IANA tz).
// Source: github.com/mwgg/Airports (MIT). The same JSON will be bundled into the Android app (offline estimates).
// Run: deno run --allow-net --allow-write scripts/import-airports.ts
const SRC = "https://raw.githubusercontent.com/mwgg/Airports/master/airports.json";

interface A { icao: string; iata: string; name: string; city: string; country: string; lat: number; lon: number; tz: string }

const data: Record<string, A> = await (await fetch(SRC)).json();
const q = (s: string | null | undefined) => (s == null || s === "" ? "null" : `'${s.replaceAll("'", "''")}'`);
const rows = Object.values(data)
  .filter((a) => /^[A-Z]{3}$/.test(a.iata ?? "") && a.tz && Number.isFinite(a.lat) && Number.isFinite(a.lon))
  .sort((a, b) => a.iata.localeCompare(b.iata));

// a few IATA codes appear twice in the source (closed airports); keep the first with a 4-letter ICAO
const seen = new Set<string>();
const values: string[] = [];
for (const a of rows) {
  if (seen.has(a.iata)) continue;
  seen.add(a.iata);
  const icao = /^[A-Z0-9]{4}$/.test(a.icao ?? "") ? q(a.icao) : "null";
  values.push(`(${q(a.iata)},${icao},${q(a.name)},${q(a.city)},${q((a.country ?? "").slice(0, 2))},${a.lat.toFixed(5)},${a.lon.toFixed(5)},${q(a.tz)})`);
}
const sql = `-- Generated by scripts/import-airports.ts from mwgg/Airports (MIT). ${values.length} airports.
insert into public.airports (iata, icao, name, city, country, lat, lon, tz) values
${values.join(",\n")}
on conflict (iata) do update set icao = excluded.icao, name = excluded.name, city = excluded.city,
  country = excluded.country, lat = excluded.lat, lon = excluded.lon, tz = excluded.tz;
`;
await Deno.writeTextFile(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`wrote supabase/seed.sql with ${values.length} airports`);
